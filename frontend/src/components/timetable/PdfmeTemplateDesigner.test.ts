import { describe, expect, it } from 'vitest'
import { generate } from '@pdfme/generator'
import { image, line, rectangle, text } from '@pdfme/schemas'
import { createPdfmeTemplate, exportablePdfmeTemplate, generatePdfmePdf, hydratePdfmeInputs, materializePdfmeTemplate, persistableTemplate, timetableGeometry } from './PdfmeTemplateDesigner'
import type { TimetableSession } from '../../lib/timetable'

const context = {
  institution: { id: 'i', name: 'College A', institutionType: 'College', address: 'Campus', active: true },
  department: { id: 'd', institutionId: 'i', name: 'Computer Science', active: true },
  semester: { id: 's', departmentId: 'd', number: 1, label: 'Semester 1', active: true },
  group: { id: 'g', departmentId: 'd', semesterId: 's', academicTermId: 't', sectionName: 'A', label: 'A', active: true },
  term: { id: 't', institutionId: 'i', academicYear: '2026', term: 'Spring', active: true },
  resources: { subjects: [], teachers: [], rooms: [] },
  sessions: [],
  workingDays: ['monday', 'tuesday', 'wednesday', 'thursday', 'friday'] as TimetableSession['day'][],
}

describe('pdfme timetable template POC', () => {
  it('creates A4 landscape templates with dynamic fields and seven signatures', () => {
    const result = createPdfmeTemplate(context, 7)
    expect(result.template.basePdf).toMatchObject({ width: 297, height: 210 })
    expect(result.template.schemas[0].filter((item) => item.name.startsWith('signature_label_'))).toHaveLength(7)
    expect(result.inputs.institution_name).toBe('College A')
  })

  it('shares protected five/six-day grid geometry with PDF schemas', () => {
    const fiveDay = createPdfmeTemplate(context, 0).template.schemas[0].filter((item) => item.name.startsWith('timetable_grid_'))
    const sixDay = createPdfmeTemplate({ ...context, workingDays: [...context.workingDays, 'saturday'] }, 0).template.schemas[0].filter((item) => item.name.startsWith('timetable_grid_'))
    expect(fiveDay).toHaveLength(18)
    expect(sixDay).toHaveLength(19)
    expect(timetableGeometry(context.workingDays).dayWidth).toBe(49.8)
    expect(timetableGeometry(context.workingDays).startMinutes).toBe(540)
    expect(timetableGeometry(context.workingDays).endMinutes).toBe(1020)
    expect(timetableGeometry(context.workingDays, true).top).toBe(71)
    expect(timetableGeometry(context.workingDays, true).gridBottom).toBe(159)
    expect(timetableGeometry(context.workingDays, true, 'compact').top).toBe(68)
    expect(timetableGeometry(context.workingDays, true, 'spacious').top).toBe(74)
    const compactTemplate = { ...createPdfmeTemplate(context, 0, 'data:image/png;base64,iVBORw0KGgo=', 'compact').template, __schedaroAssets: { letterhead: 'data:image/png;base64,iVBORw0KGgo=' } }
    const spacious = materializePdfmeTemplate({ ...compactTemplate, __schedaroLayout: { mode: 'automatic', headerSpacing: 'spacious' } } as any, context)
    const compactDay = compactTemplate.schemas[0].find((item) => item.name === 'day_monday') as any
    const spaciousDay = spacious.schemas[0].find((item) => item.name === 'day_monday') as any
    expect(spaciousDay.position.y - compactDay.position.y).toBe(6)
    expect(timetableGeometry([...context.workingDays, 'saturday']).dayWidth).toBe(41.5)
    expect(fiveDay.some((item) => item.name === 'timetable_grid_hour-1')).toBe(true)
    const gridLine = createPdfmeTemplate(context, 0).template.schemas[0].find((item) => item.name === 'timetable_grid_outer-top') as Record<string, unknown>
    expect(gridLine.color).toBe('#aeb6c2')
    expect(gridLine.opacity).toBe(1)
    expect(gridLine.height).toBe(0.7)
    const leftBorder = createPdfmeTemplate(context, 0).template.schemas[0].find((item) => item.name === 'timetable_grid_outer-left') as any
    expect(leftBorder.rotate).toBe(90)
    expect(leftBorder.position.y).toBeCloseTo(104.75, 2)
    const letterhead = createPdfmeTemplate(context, 7, 'data:image/png;base64,iVBORw0KGgo=')
    const letterheadGeometry = timetableGeometry(context.workingDays, true)
    const letterheadSchemas = letterhead.template.schemas[0] as any[]
    expect(letterheadSchemas.find((item) => item.name === 'timetable_title').position.y + 7).toBeLessThanOrEqual(letterheadGeometry.top)
    for (const item of letterheadSchemas.filter((schema) => String(schema.name).startsWith('signature_'))) expect(item.position.y + item.height).toBeLessThanOrEqual(202)
  })

  it('removes only legacy autogenerated signature lines while preserving explicit saved signatures', () => {
    const legacy = createPdfmeTemplate(context, 3)
    const normalized = materializePdfmeTemplate(legacy.template, context)
    expect((normalized.schemas[0] as any[]).some((item) => String(item.name).startsWith('signature_line_'))).toBe(false)
    const explicit = persistableTemplate(legacy.template, legacy.inputs)
    const retained = materializePdfmeTemplate({ ...legacy.template, ...explicit } as typeof legacy.template, context)
    expect((retained.schemas[0] as any[]).some((item) => String(item.name).startsWith('signature_line_'))).toBe(true)
  })

  it('persists editable inputs while replacing protected timetable data for the active context', () => {
    const saved = createPdfmeTemplate(context, 1)
    const editable = { ...saved.template, schemas: [[...(saved.template.schemas[0] as any[]), { name: 'custom_text_1', type: 'text', position: { x: 20, y: 20 }, width: 80, height: 8 }]] }
    const persisted = persistableTemplate(editable, { ...saved.inputs, custom_text_1: 'Approved timetable', letterhead: 'data:image/png;base64,iVBORw0KGgo=' })
    const nextSession: TimetableSession = { id: 'new-session', classGroupId: 'g', day: 'monday', startTime: '09:00', endTime: '10:00', subjectId: 'subject', teacherId: 'teacher', roomId: 'room', type: 'Lecture' }
    const nextContext = { ...context, sessions: [nextSession], resources: { subjects: [{ id: 'subject', name: 'Algorithms', active: true }], teachers: [{ id: 'teacher', name: 'Dr. Rao', active: true }], rooms: [{ id: 'room', name: 'A-101', active: true }] } }
    const template = materializePdfmeTemplate({ ...editable, ...persisted } as typeof saved.template, nextContext)
    const inputs = hydratePdfmeInputs(template, nextContext, { letterhead: 'data:image/png;base64,iVBORw0KGgo=' }, { custom_text_1: 'Approved timetable' })
    expect(inputs[`session_subject_${nextSession.id}`]).toContain('Algorithms')
    expect(inputs.custom_text_1).toBe('Approved timetable')
    expect(inputs.letterhead).toContain('data:image/png')
  })

  it('builds readable session hierarchy for varied durations and session types', () => {
    const populated = { ...context, workingDays: [...context.workingDays, 'saturday'] as TimetableSession['day'][], resources: { subjects: [{ id: 's1', name: 'Algorithms and Data Structures', active: true }, { id: 's2', name: 'Laboratory Systems', active: true }, { id: 's3', name: 'Tutorial', active: true }], teachers: [{ id: 't1', name: 'Instructor Two', active: true }], rooms: [{ id: 'r1', name: 'Room 305', active: true }] }, sessions: [
      { id: 'short', classGroupId: 'g', day: 'monday' as const, startTime: '09:00', endTime: '09:30', subjectId: 's3', teacherId: 't1', roomId: 'r1', type: 'Tutorial' as const },
      { id: 'lecture', classGroupId: 'g', day: 'tuesday' as const, startTime: '10:00', endTime: '11:00', subjectId: 's1', teacherId: 't1', roomId: 'r1', type: 'Lecture' as const },
      { id: 'long', classGroupId: 'g', day: 'wednesday' as const, startTime: '11:00', endTime: '12:30', subjectId: 's2', teacherId: 't1', roomId: 'r1', type: 'Laboratory' as const },
    ] }
    const result = createPdfmeTemplate(populated, 0)
    const schemas = result.template.schemas[0] as any[]
    expect(schemas.some((item) => item.name === 'session_info_short')).toBe(true)
    expect(schemas.some((item) => item.name === 'session_subject_lecture')).toBe(true)
    expect(schemas.find((item) => item.name === 'session_card_long').color).toBe('#eef8f1')
    const geometry = timetableGeometry(populated.workingDays)
    for (const item of schemas.filter((schema) => String(schema.name).startsWith('session_'))) {
      expect(item.position.y).toBeGreaterThanOrEqual(geometry.gridTop)
      expect(item.position.y + item.height).toBeLessThanOrEqual(geometry.gridBottom + 0.01)
    }
    expect(schemas.filter((item) => String(item.name).startsWith('signature_'))).toHaveLength(0)
  })

  it('renders protected timetable schemas into the generated PDF input model', async () => {
    const populated = { ...context, resources: { subjects: [{ id: 'subject', name: 'Algorithms', active: true }], teachers: [{ id: 'teacher', name: 'Dr. Rao', active: true }], rooms: [{ id: 'room', name: 'A-101', active: true }] }, sessions: [{ id: 'session-1', classGroupId: 'g', day: 'monday' as const, startTime: '09:00', endTime: '12:00', subjectId: 'subject', teacherId: 'teacher', roomId: 'room', type: 'Lecture' as const }] }
    const result = createPdfmeTemplate(populated, 0)
    const pdf = await generatePdfmePdf(result.template, result.inputs)
    expect((exportablePdfmeTemplate(result.template).schemas[0][0] as Record<string, unknown>).readOnly).toBeUndefined()
    expect(result.template.schemas[0].some((item) => item.name === 'session_subject_session-1')).toBe(true)
    expect(result.template.schemas[0].some((item) => item.name === 'session_card_session-1')).toBe(true)
    expect(result.inputs['session_subject_session-1']).toContain('Algorithms')
    expect(new TextDecoder().decode(pdf.slice(0, 5))).toBe('%PDF-')
  })

  it('generates a real PDF from the POC template', async () => {
    const result = createPdfmeTemplate(context, 3)
    const pdf = await generate({ template: result.template, inputs: [result.inputs], plugins: { text, image, line, rectangle } })
    expect(new TextDecoder().decode(pdf.slice(0, 5))).toBe('%PDF-')
    expect(pdf.byteLength).toBeGreaterThan(1000)
  })
})
